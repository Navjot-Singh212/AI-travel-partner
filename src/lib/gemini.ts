export function getGeminiApiKey(): string {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey.trim() === "" || apiKey === "your_gemini_api_key_here") {
    throw new Error(
      "GEMINI_API_KEY is not configured on the server. Please add your free-tier key to .env.local (see .env.example). Never paste your key in chat or client code."
    );
  }
  return apiKey.trim();
}

/**
 * Low-level call to Gemini 2.5 Flash with free search grounding
 */
export async function callGemini25Flash(params: {
  systemInstruction?: string;
  contents: Array<{
    role?: string;
    parts: Array<
      | { text: string }
      | { inlineData: { mimeType: string; data: string } }
    >;
  }>;
  enableSearchGrounding?: boolean;
}): Promise<{ text: string; sources: GroundingSource[] }> {
  const apiKey = getGeminiApiKey();
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`;

  const requestBody: Record<string, unknown> = {
    contents: params.contents,
    generationConfig: {
      temperature: 0.3, // Lower temperature to reduce hallucinations
      topP: 0.95,
      maxOutputTokens: 2048,
    },
  };

  if (params.systemInstruction) {
    requestBody.systemInstruction = {
      parts: [{ text: params.systemInstruction }],
    };
  }

  // Free-tier Google Search grounding
  if (params.enableSearchGrounding !== false) {
    requestBody.tools = [
      {
        googleSearch: {},
      },
    ];
  }

  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify(requestBody),
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    const message = errorData?.error?.message || response.statusText;
    const status = response.status;

    if (status === 429) {
      throw new Error(
        "Free Tier quota limit reached (HTTP 429). Please wait a moment before trying again. No paid overage charges will be incurred."
      );
    }
    if (status === 403) {
      throw new Error(
        `Gemini API access denied (HTTP 403): ${message}. Verify your key is active and belongs to an unbilled Free Tier project in Google AI Studio.`
      );
    }
    if (status === 400 && message.toLowerCase().includes("search")) {
      // If search grounding is unavailable on this free project tier, retry without search tool
      return callGemini25Flash({ ...params, enableSearchGrounding: false });
    }

    throw new Error(`Gemini API error (${status}): ${message}`);
  }

  const data = await response.json();
  const candidate = data?.candidates?.[0];

  if (!candidate) {
    throw new Error("No response generated by Gemini. The input might have triggered safety filters.");
  }

  const text = candidate?.content?.parts?.map((p: { text?: string }) => p.text || "").join("") || "";

  // Extract grounding citations if present
  const sources: GroundingSource[] = [];
  const groundingMetadata = candidate?.groundingMetadata;

  if (groundingMetadata?.groundingChunks) {
    for (const chunk of groundingMetadata.groundingChunks) {
      if (chunk?.web?.uri) {
        sources.push({
          title: chunk.web.title || new URL(chunk.web.uri).hostname,
          url: chunk.web.uri,
        });
      }
    }
  }

  // Deduplicate sources by URL
  const uniqueSources = sources.filter(
    (s, index, self) => index === self.findIndex((t) => t.url === s.url)
  );

  return { text, sources: uniqueSources };
}

/**
 * Clean and parse JSON from model output that might be wrapped in ```json ... ```
 */
export function extractJsonFromText<T>(text: string): T {
  let cleaned = text.trim();
  // Strip markdown code fences if present
  const jsonMatch = cleaned.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
  if (jsonMatch) {
    cleaned = jsonMatch[1].trim();
  }
  return JSON.parse(cleaned) as T;
}
